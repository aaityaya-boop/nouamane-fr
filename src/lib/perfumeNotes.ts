/**
 * Normalizes text for matching
 */
function cleanKey(str: string): string {
  return str
    .toLowerCase()
    .trim()
    .replace(/[.;,]+$/, '')
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, (match) => {
      // keep basic accented matches or flatten
      return match;
    });
}

/**
 * Translates a perfume note item safely into the target locale.
 * Handles single notes, compound notes ("X et Y"), and multi-line notes.
 */
export function translatePerfumeNote(rawNote: string, locale: 'fr' | 'ar' | 'en'): string {
  if (!rawNote || locale === 'fr') return rawNote;

  const trimmed = rawNote.trim();
  if (!trimmed) return rawNote;

  // Handle multi-line notes in raw data (e.g. "Lavande\nMenthe")
  if (trimmed.includes('\n')) {
    const lines = trimmed.split('\n').filter(Boolean);
    const translatedLines = lines.map(l => translateSingleNote(l, locale));
    return locale === 'ar' ? translatedLines.join('، ') : translatedLines.join(', ');
  }

  // Handle compound "et" / "and" (e.g. "Gingembre et Bergamote")
  if (/\b et \b/i.test(trimmed)) {
    const parts = trimmed.split(/\b et \b/i);
    const translatedParts = parts.map(p => translateSingleNote(p, locale));
    return locale === 'ar' ? translatedParts.join(' و ') : translatedParts.join(' & ');
  }

  return translateSingleNote(trimmed, locale);
}

function translateSingleNote(note: string, locale: 'ar' | 'en'): string {
  const norm = note.toLowerCase().trim().replace(/[.;,]+$/, '');

  // 1. Exact match
  if (NOTES_TRANSLATIONS[norm]) {
    return NOTES_TRANSLATIONS[norm][locale];
  }

  // 2. Partial prefix / substring match in dictionary
  for (const [key, val] of Object.entries(NOTES_TRANSLATIONS)) {
    if (norm === key || norm.startsWith(key + ' ') || norm.endsWith(' ' + key)) {
      return val[locale];
    }
  }

  // 3. Fallback: return original note cleanly
  return note;
}

/**
 * Translates olfactory family into target locale
 */
export function translateOlfactoryFamily(family: string, locale: 'fr' | 'ar' | 'en'): string {
  if (!family || locale === 'fr') return family;
  const norm = family.toLowerCase().trim();
  if (FAMILIES_TRANSLATIONS[norm]) {
    return FAMILIES_TRANSLATIONS[norm][locale];
  }
  for (const [key, val] of Object.entries(FAMILIES_TRANSLATIONS)) {
    if (norm.includes(key)) {
      return val[locale];
    }
  }
  return family;
}

/**
 * Translates perfect season into target locale
 */
export function translateSeason(season: string, locale: 'fr' | 'ar' | 'en'): string {
  if (!season || locale === 'fr') return season;
  const norm = season.toLowerCase().trim();
  if (SEASONS_TRANSLATIONS[norm]) {
    return SEASONS_TRANSLATIONS[norm][locale];
  }
  return season;
}

/**
 * Translates concentration into target locale
 */
export function translateConcentration(concentration: string, locale: 'fr' | 'ar' | 'en'): string {
  if (!concentration || locale === 'fr') return concentration;
  const norm = concentration.toLowerCase().trim();
  if (CONCENTRATIONS_TRANSLATIONS[norm]) {
    return CONCENTRATIONS_TRANSLATIONS[norm][locale];
  }
  if (norm.includes('extrait')) {
    return CONCENTRATIONS_TRANSLATIONS["extrait de parfum"][locale];
  }
  if (norm.includes('toilette')) {
    return CONCENTRATIONS_TRANSLATIONS["eau de toilette"][locale];
  }
  return CONCENTRATIONS_TRANSLATIONS["eau de parfum (haute concentration)"][locale];
}
