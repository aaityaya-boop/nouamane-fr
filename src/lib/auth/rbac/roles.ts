export const ROLE_MAP = new Map<string, RoleDefinition>(
  ALL_ROLES.map((r) => [r.id, r])
);

/**
 * Get role definition by ID with graceful fallback for legacy roles
 */
export function getRoleDefinition(roleId: string | null | undefined): RoleDefinition {
  if (!roleId) return ROLE_MAP.get('GUEST_VIEWER')!;
  
  // Normal lookup
  const found = ROLE_MAP.get(roleId.toUpperCase());
  if (found) return found;

  // Handle legacy roles
  if (roleId === 'SUPER_ADMIN' || roleId === 'ADMIN' || roleId === 'OWNER') {
    return ROLE_MAP.get('OWNER')!;
  }

  return {
    id: roleId,
    name: roleId,
    department: 'Direction & Fondateurs',
    badgeBg: 'bg-zinc-500/10',
    badgeText: 'text-zinc-400',
    badgeBorder: 'border-zinc-500/20',
    description: 'Rôle personnalisé',
    defaultPermissions: ['dashboard.view', 'suggestions.create', 'reclamations.create'],
  };
}
