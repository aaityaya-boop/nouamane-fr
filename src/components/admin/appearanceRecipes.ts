import { AdminDesignConfig } from '@/context/AdminThemeContext';

export type PairedRecipeCategory = 'all' | 'glass' | 'luxury' | 'modern' | 'compact';

export interface PairedCompleteRecipe {
  id: string;
  name: string;
  desc: string;
  category: Exclude<PairedRecipeCategory, 'all'>;
  lightSwatch: [string, string, string];
  darkSwatch: [string, string, string];
  basePatch: Partial<AdminDesignConfig>;
  lightOverrides?: Partial<AdminDesignConfig>;
  darkOverrides?: Partial<AdminDesignConfig>;
}

export function resolvePairedRecipePatch(
  rec: PairedCompleteRecipe,
  mode: 'light' | 'dark'
): Partial<AdminDesignConfig> {
  return {
    customBgColor: '',
    customCardColor: '',
    customTextColor: '',
    ...rec.basePatch,
    ...(mode === 'light' ? rec.lightOverrides : rec.darkOverrides),
  };
}

